const fs = require('fs');
const path = require('path');
const assert = require('assert/strict');
const root=process.cwd();
const ts=require(path.join(root,'node_modules/typescript'));
const {DOMParser,XMLSerializer}=require(path.join(root,'node_modules/@xmldom/xmldom'));
const code=ts.transpileModule(fs.readFileSync('apps/desktop/src/renderer/features/annotations/annotations.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const m={exports:{}};
require('vm').runInNewContext(code,{exports:m.exports,DOMParser,XMLSerializer,crypto:require('crypto').webcrypto,console});
const {importKml,parseAnnotationProject,exportKml,visibleAnnotations,compactAnnotationProject}=m.exports;
const source=fs.readFileSync(process.argv[2] || '../RawData/annotations/annotations.json','utf8');
const start=Date.now();
const p=parseAnnotationProject(source);
assert.equal(p.nodes.length,541);
assert.equal(p.nodes.filter(n=>n.kind==='folder').length,80);
assert.equal(p.nodes.filter(n=>n.kind==='point').length,265);
assert.equal(p.nodes.filter(n=>n.kind==='route').length,196);
parseAnnotationProject(JSON.stringify(p));
const hasXml = project => ['sourceKml','kmlDocumentXml'].some(key => key in project) || project.nodes.some(n => 'sourceXml' in n);
assert(!hasXml(p), 'JSON must not retain KML payloads');
const legacy = {...p, sourceKml:'<kml/>', kmlDocumentXml:'<Document/>', nodes:p.nodes.map(n=>({...n,sourceXml:'<Placemark/>'}))};
const compacted = compactAnnotationProject(legacy);
assert(!hasXml(compacted));
const legacyParsed = parseAnnotationProject(JSON.stringify(legacy));
assert.equal(JSON.stringify(legacyParsed), JSON.stringify(p));
const output=exportKml(p);
const again=importKml(output);
assert.equal(again.nodes.length,p.nodes.length);
assert(!hasXml(again), "KML import must immediately produce plain JSON");
for(const node of p.nodes){
 const actual=again.nodes.find(n=>n.id===node.id);
 if(node.kind==='folder')assert.equal(actual.open,node.open);
 for(const field of ['kind','name','description','visible','parentId','coordinates','altitudeMode','style'])assert.equal(JSON.stringify(actual[field]),JSON.stringify(node[field]),`${node.id}: ${field}`);
}
const child=p.nodes.find(n=>n.kind==='point');
const folder=p.nodes.find(n=>n.id===child.parentId); folder.visible=false;
assert(!visibleAnnotations(p).some(n=>n.id===child.id));
const bad=JSON.parse(JSON.stringify(p));bad.nodes[0].parentId=bad.nodes[0].id;
assert.throws(()=>parseAnnotationProject(JSON.stringify(bad)));
assert.throws(()=>importKml('<!DOCTYPE kml><kml/>'));
assert.throws(()=>importKml('<kml><Placemark><Point><coordinates>999,0</coordinates></Point></Placemark></kml>'));
const newId=require('crypto').randomUUID();
p.nodes.push({...child,id:newId,parentId:null,name:'测试 & <地标>',description:'<script>不执行</script>',coordinates:[[116.4,39.9,123]],style:{color:'#12ab34',opacity:0.5,width:4}});
const newPoint=importKml(exportKml(p)).nodes.find(n=>n.id===newId);
assert.equal(newPoint.name,'测试 & <地标>');assert.equal(newPoint.description,'<script>不执行</script>');
console.log(JSON.stringify({name:p.name,folders:80,points:265,routes:196,coordinateCount:p.nodes.filter(n=>n.id!==newId).reduce((s,n)=>s+n.coordinates.length,0),visible:visibleAnnotations(p).length,roundtrip:'passed',invalidInput:'rejected',milliseconds:Date.now()-start},null,2));
